/** Reuse reviewed case images, captions and baked-in privacy edits. Never raw uploads. */
function screens(study: CaseStudy, id: string) {
  const module = study.modules.find((item) => item.id === id);
  if (!module) throw new Error(`Missing case module: ${id}`);
  return module.images;
}
function image(image: CaseImage, label: string): CaseImage {
  return {
    ...image,
    label,
    ...(image.height > image.width ? { mobileFullWidth: true } : {}),
    ...(image.mobile
      ? { mobile: { ...image.mobile, label, mobileFullWidth: true } }
      : {}),
  };
}
