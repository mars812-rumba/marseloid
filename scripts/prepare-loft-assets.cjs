/** Reviewed owner screenshots only. Removes browser/OS bars; preserves site UI. */
const sharp = require("sharp");
const fs = require("fs");
const path = require("path");
const desktop = [
  "home",
  "sets",
  "products",
  "colors",
  "constructor",
  "production",
];
const mobile = [
  "home",
  "sets",
  "kit-detail",
  "colors",
  "constructor",
  "advantages",
  "production",
];
(async () => {
  const assets = {};
  fs.mkdirSync("public/cases/loft-fire", { recursive: true });
  for (const [device, names] of [
    ["desktop", desktop],
    ["mobile", mobile],
  ]) {
    const dir = `screenshots/loft-fire/${device}`;
    const files = fs.readdirSync(dir).sort();
    for (let i = 0; i < files.length; i++) {
      const top = device === "desktop" ? 186 : [0, 3].includes(i) ? 140 : 56;
      const crop =
        device === "desktop"
          ? { left: 0, top, width: 1898, height: 844 }
          : { left: 0, top, width: 576, height: 1210 - top };
      const name = `${names[i]}-${device}`;
      const file = `public/cases/loft-fire/${name}.webp`;
      const info = await sharp(path.join(dir, files[i]))
        .extract(crop)
        .resize({
          width: device === "desktop" ? 1440 : 576,
          withoutEnlargement: true,
        })
        .webp({ quality: 86 })
        .toFile(file);
      assets[name] = {
        src: `/cases/loft-fire/${name}.webp`,
        width: info.width,
        height: info.height,
      };
    }
  }
  fs.writeFileSync(
    "lib/loft-assets.ts",
    "// Generated by scripts/prepare-loft-assets.cjs from reviewed screenshots.\nexport const loftAssets = " +
      JSON.stringify(assets, null, 2) +
      " as const;\n",
  );
})();
